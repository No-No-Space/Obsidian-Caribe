#!/usr/bin/env python3
"""Build theme.css for the Caribe Obsidian theme.

    python build.py                  # build theme.css
    python build.py --check          # exit 1 if theme.css is out of date
    python build.py --tokens PATH    # refresh tokens/tokens.json from the full
                                     # AAJ Design System tokens.json, then build

theme.css = header + @font-face (fonts/ embedded as base64 when present)
            + generated colour tokens + src/*.css (in name order).

No hex code is written by hand in src/: every colour is a var(--caribe-*)
generated here from tokens/tokens.json.
"""
from __future__ import annotations

import argparse
import base64
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TOKENS = ROOT / "tokens" / "tokens.json"
FONTS = ROOT / "fonts"
SRC = ROOT / "src"
OUT = ROOT / "theme.css"
MANIFEST = ROOT / "manifest.json"

# family, weight, file stem, local() names tried first
FONT_FACES = [
    ("Gully", 700, "Gully-Bold", ["Gully Bold", "Gully-Bold"]),
    ("Moderustic", 400, "Moderustic-Regular", ["Moderustic", "Moderustic Regular", "Moderustic-Regular"]),
    ("Moderustic", 700, "Moderustic-Bold", ["Moderustic Bold", "Moderustic-Bold"]),
    ("Fliege Mono", 300, "FliegeMono-Light", ["Fliege Mono Light", "FliegeMono-Light"]),
    ("Fliege Mono", 400, "FliegeMono-Regular", ["Fliege Mono", "Fliege Mono Regular", "FliegeMono-Regular"]),
    ("Fliege Mono", 500, "FliegeMono-Medium", ["Fliege Mono Medium", "FliegeMono-Medium"]),
]
FORMATS = {".woff2": "woff2", ".woff": "woff", ".ttf": "truetype", ".otf": "opentype"}

# Only these keys are kept when refreshing from the full tokens.json.
KEEP_PREFIXES = ("color-", "bg-", "text-", "seq-neutro-", "seq-mar-1", "seq-mar-5",
                 "shadow-color", "focus-ring", "state-primary", "state-secondary",
                 "state-mar-caribe", "state-disabled", "table-", "row-")


def resolve(tokens: list[dict]) -> dict[str, str]:
    raw = {t["name"]: t["value"] for t in tokens}

    def get(name: str, seen=()) -> str:
        v = raw[name]
        m = re.fullmatch(r"\{([\w-]+)\}", v)
        if m:
            if m.group(1) in seen:
                raise ValueError(f"circular token reference: {name}")
            return get(m.group(1), seen + (name,))
        return v

    return {n: get(n).lower() for n in raw}


def rgb(hexv: str) -> str:
    h = hexv.lstrip("#")
    return ", ".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))


def refresh_tokens(path: Path) -> None:
    full = json.loads(path.read_text(encoding="utf-8"))
    kept = [{"name": t["name"], "value": t["value"]} for t in full["color"]["tokens"]
            if t["name"].startswith(KEEP_PREFIXES)]
    snap = json.loads(TOKENS.read_text(encoding="utf-8"))
    snap["color"]["tokens"] = kept
    TOKENS.write_text(json.dumps(snap, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"tokens/tokens.json refreshed: {len(kept)} colour tokens")


def tokens_css() -> str:
    data = json.loads(TOKENS.read_text(encoding="utf-8"))
    values = resolve(data["color"]["tokens"])
    lines = ["/* ---- Caribe colour tokens (generated by build.py; do not edit) ---- */", "body {"]
    for name, v in values.items():
        lines.append(f"  --caribe-{name}: {v};")
        if re.fullmatch(r"#[0-9a-f]{6}", v):
            lines.append(f"  --caribe-{name}-rgb: {rgb(v)};")
    lines.append("}")
    return "\n".join(lines)


def fonts_css() -> tuple[str, list[str]]:
    out, missing = ["/* ---- Fonts (all SIL OFL 1.1; licences in fonts/) ---- */"], []
    for family, weight, stem, locals_ in FONT_FACES:
        srcs = [f'local("{n}")' for n in locals_]
        f = next((FONTS / f"{stem}{ext}" for ext in FORMATS if (FONTS / f"{stem}{ext}").exists()), None)
        if f:
            b64 = base64.b64encode(f.read_bytes()).decode("ascii")
            mime = "font/" + FORMATS[f.suffix].replace("truetype", "ttf").replace("opentype", "otf")
            srcs.append(f'url("data:{mime};base64,{b64}") format("{FORMATS[f.suffix]}")')
        else:
            missing.append(stem)
        out.append(
            "@font-face {\n"
            f'  font-family: "{family}";\n'
            f"  font-weight: {weight};\n"
            "  font-style: normal;\n"
            "  font-display: swap;\n"
            f"  src: {', '.join(srcs)};\n"
            "}"
        )
    return "\n".join(out), missing


def build() -> tuple[str, list[str]]:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    header = (
        f"/* {manifest['name']} {manifest['version']} for Obsidian, by {manifest['author']}.\n"
        " * Built on the Caribe (AAJ) design system. GENERATED FILE: edit src/ and run build.py. */"
    )
    fonts, missing = fonts_css()
    parts = [header, fonts, tokens_css()]
    for f in sorted(SRC.glob("*.css")):
        parts.append(f"/* ==== {f.name} ==== */\n" + f.read_text(encoding="utf-8").strip())
    return "\n\n".join(parts) + "\n", missing


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if theme.css is out of date")
    ap.add_argument("--tokens", type=Path, help="full AAJ tokens.json to refresh the snapshot from")
    a = ap.parse_args()
    if a.tokens:
        refresh_tokens(a.tokens)
    css, missing = build()
    if a.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != css:
            print("theme.css is out of date: run python build.py", file=sys.stderr)
            return 1
        print("theme.css is up to date")
        return 0
    OUT.write_text(css, encoding="utf-8", newline="\n")
    print(f"theme.css written ({len(css.encode()) / 1024:.0f} KB)")
    if missing:
        print("Not embedded (falls back to installed fonts; needed for iPad): "
              + ", ".join(missing), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
